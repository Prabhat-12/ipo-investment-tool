-- 2. Investment Group Invite Codes
-- Each group gets one unique alphanumeric invite code.
-- Members share this code; anyone with it can join the group.

alter table family_groups
  add column if not exists invite_code text unique;

-- Generate a random 8-char alphanumeric code for existing groups
-- (Run once; new groups will get codes generated by the app)
update family_groups
set invite_code = upper(
  substring(md5(random()::text || id::text), 1, 4) ||
  substring(md5(id::text || now()::text), 1, 4)
)
where invite_code is null;

-- Index for fast lookup when joining with a code
create index if not exists idx_family_groups_invite_code
  on family_groups (invite_code);

