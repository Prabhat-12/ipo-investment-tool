-- 1. Guest Visits Table
-- Tracks every person who enters the app via Guest Access
create table if not exists guest_visits (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  visited_at timestamptz not null default now()
);

-- Allow anyone (including unauthenticated visitors) to insert a visit row
alter table guest_visits enable row level security;
create policy "anon can log visit" on guest_visits
  for insert with check (true);

-- Only authenticated users can read visit logs (for your own admin view)
create policy "auth can read visits" on guest_visits
  for select using (auth.role() = 'authenticated');

